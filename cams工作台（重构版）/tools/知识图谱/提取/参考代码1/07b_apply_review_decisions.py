def enrich_rewritten_edge(edge: dict[str, Any], nodes_by_name: dict[str, dict[str, Any]]) -> dict[str, Any]:
    item = dict(edge)
    source_name = str(item.get("source_name") or "")
    target_name = str(item.get("target_name") or "")
    source = nodes_by_name.get(source_name, {})
    target = nodes_by_name.get(target_name, {})
    item.setdefault("source_node_id", source.get("node_id", ""))
    item.setdefault("target_node_id", target.get("node_id", ""))
    item.setdefault("source_type", source.get("type", ""))
    item.setdefault("target_type", target.get("type", ""))
    if not item.get("edge_id"):
        item["edge_id"] = stable_id(
            "gaodai_shang:review-edge",
            [
                str(item.get("source_node_id") or source_name),
                str(item.get("target_node_id") or target_name),
                str(item.get("type") or ""),
            ],
        )
    return item


def merge_node_alias(final_nodes: list[dict[str, Any]], target_name: str, source: dict[str, Any], decision: dict[str, Any]) -> bool:
    if not target_name:
        return False
    source_name = str(source.get("name") or "")
    for node in final_nodes:
        if node.get("name") != target_name and node.get("node_id") != decision.get("rewritten_item", {}).get("target_node_id"):
            continue
        aliases = list(node.get("aliases") or [])
        if source_name and source_name != node.get("name") and source_name not in aliases:
            aliases.append(source_name)
        node["aliases"] = aliases
        merged = list(node.get("step7_merged_from_review_items") or [])
        merged.append(
            {
                "source_node_id": source.get("node_id", ""),
                "source_name": source_name,
                "source_type": source.get("type", ""),
                "evidence_span": source.get("evidence_span", ""),
                "decision_id": decision.get("decision_id", ""),
                "basis": decision.get("basis", ""),
            }
        )
        node["step7_merged_from_review_items"] = merged
        return True
    return False


def owner_exists(rule_case: dict[str, Any], final_nodes: list[dict[str, Any]]) -> bool:
    owner_id = str(rule_case.get("owner_node_id") or "")
    owner_name = str(rule_case.get("owner_name") or "")
    for node in final_nodes:
        if owner_id and node.get("node_id") == owner_id:
            return True
        if owner_name and node.get("name") == owner_name:
            return True
    return False


def edge_endpoints_exist(edge: dict[str, Any], final_nodes: list[dict[str, Any]]) -> tuple[bool, list[str]]:
    source_id = str(edge.get("source_node_id") or "")
    target_id = str(edge.get("target_node_id") or "")
    source_name = str(edge.get("source_name") or "")
    target_name = str(edge.get("target_name") or "")
    node_ids = {str(node.get("node_id") or "") for node in final_nodes if node.get("node_id")}
    node_names = {str(node.get("name") or "") for node in final_nodes if node.get("name")}
    missing: list[str] = []
    if source_id:
        if source_id not in node_ids:
            missing.append(f"source:{source_name or source_id}")
    elif source_name not in node_names:
        missing.append(f"source:{source_name or '<missing>'}")
    if target_id:
        if target_id not in node_ids:
            missing.append(f"target:{target_name or target_id}")
    elif target_name not in node_names:
        missing.append(f"target:{target_name or '<missing>'}")
    return (not missing, missing)


def is_core_target_layer(target_layer: str) -> bool:
    return target_layer in {"core", "explicit_core"}


def write_report(
    path: Path,
    final_core_nodes: list[dict[str, Any]],
    final_core_edges: list[dict[str, Any]],
    final_app_nodes: list[dict[str, Any]],
    final_app_edges: list[dict[str, Any]],
    final_rule_cases: list[dict[str, Any]],
    final_groups: list[dict[str, Any]],
    final_group_edges: list[dict[str, Any]],
    archived: list[dict[str, Any]],
    deferred: list[dict[str, Any]],
    traces: list[dict[str, Any]],
) -> None:
    decision_counts = Counter(str(row.get("result") or "") for row in traces)
    node_type_counts = Counter(str(row.get("type") or "") for row in final_core_nodes + final_app_nodes)
    edge_type_counts = Counter(str(row.get("type") or "") for row in final_core_edges + final_app_edges)
    rule_case_owner_counts = Counter(str(row.get("owner_type") or "") for row in final_rule_cases)

    group_type_counts = Counter(str(row.get("group_type") or "") for row in final_groups)
    group_edge_type_counts = Counter(str(row.get("type") or "") for row in final_group_edges)

    lines = [
        "# v4.4 Step 7B Review Landing Report",
        "",
        "## Final Import Package",
        f"- final_core_nodes: {len(final_core_nodes)}",
        f"- final_core_edges: {len(final_core_edges)}",
        f"- final_application_nodes: {len(final_app_nodes)}",
        f"- final_application_edges: {len(final_app_edges)}",
        f"- final_rule_cases: {len(final_rule_cases)}",
        f"- final_knowledge_groups: {len(final_groups)}",
        f"- final_knowledge_group_edges: {len(final_group_edges)}",
        f"- final_archived_items: {len(archived)}",
        f"- final_deferred_items: {len(deferred)}",
        f"- decision_trace_rows: {len(traces)}",
        "",
        "## Decision Results",
    ]
    for key, value in sorted(decision_counts.items()):
        lines.append(f"- {key}: {value}")

    lines.extend(["", "## Node Types"])
    for key, value in sorted(node_type_counts.items()):
        lines.append(f"- {key}: {value}")

    lines.extend(["", "## Edge Types"])
    for key, value in sorted(edge_type_counts.items()):
        lines.append(f"- {key}: {value}")

    lines.extend(["", "## Rule Case Owners"])
    if rule_case_owner_counts:
        for key, value in sorted(rule_case_owner_counts.items()):
            lines.append(f"- {key}: {value}")
    else:
        lines.append("- none")

    lines.extend(["", "## Knowledge Groups"])
    if group_type_counts:
        for key, value in sorted(group_type_counts.items()):
            lines.append(f"- {key}: {value}")
    else:
        lines.append("- none")

    lines.extend(["", "## Knowledge Group Edge Types"])
    if group_edge_type_counts:
        for key, value in sorted(group_edge_type_counts.items()):
            lines.append(f"- {key}: {value}")
    else:
        lines.append("- none")

    lines.extend(
        [
            "",
            "## Trace Policy",
            "- accept: item is written to a final import package.",
            "- rewrite: rewritten item is written to a final package; the original item is archived with the rewrite target.",
            "- reject: original item is archived and is not written to an import package.",
            "- defer: original item remains in final_review_pending.jsonl.",
            "- rule_case: only final_rule_cases.jsonl is expanded into rule-layer nodes/edges in Step 8.",
        ]
    )
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    args = parse_args()
    out_dir: Path = args.out_dir
    out_dir.mkdir(parents=True, exist_ok=True)

    explicit_core_nodes = read_jsonl(args.layer_dir / "explicit_core_nodes.jsonl")
    explicit_core_edges = read_jsonl(args.layer_dir / "explicit_core_edges.jsonl")
    existing_app_nodes = read_jsonl(args.layer_dir / "example_application_nodes.jsonl", required=False)
    existing_app_edges = read_jsonl(args.layer_dir / "example_application_edges.jsonl", required=False)
    existing_rule_cases = read_jsonl(args.layer_dir / "rule_cases.jsonl", required=False)
    rejected_archive = read_jsonl(args.layer_dir / "rejected_archive.jsonl", required=False)
    decisions = read_jsonl(args.decisions)

    final_core_nodes = [final_node(row, "core", "accepted_from_step6") for row in explicit_core_nodes]
    final_core_edges = [final_edge(row, "core", "accepted_from_step6") for row in explicit_core_edges]
    final_app_nodes = [final_node(row, "example_application", "accepted_from_step6") for row in existing_app_nodes]
    final_app_edges = [final_edge(row, "example_application", "accepted_from_step6") for row in existing_app_edges]
    final_rule_cases = [final_rule_case(row, "accepted_from_step6") for row in existing_rule_cases]

    archived = [
        archived_item(row, "rejected_before_step7", None, str(row.get("item_kind") or row.get("kind") or "unknown"))
        for row in rejected_archive
    ]
    deferred: list[dict[str, Any]] = []
    traces: list[dict[str, Any]] = []

    approved_decisions: list[dict[str, Any]] = []
    for decision in decisions:
        item = dict(decision)
        item["approval_label"] = args.approval_label
        approved_decisions.append(item)

    # Apply node decisions first so rewritten edges can resolve application-layer node ids.
    for decision in approved_decisions:
        if decision.get("item_kind") != "node":
            continue
        source = dict(decision.get("source_item") or {})
        recommendation = str(decision.get("recommendation") or "")
        target_layer = str(decision.get("target_layer") or "")

        if recommendation == "accept":
            if is_core_target_layer(target_layer):
                item = final_node(source, "core", "accepted_by_step7", decision)
                add_unique(final_core_nodes, item, node_identity)
            elif target_layer == "example_application":
                item = final_node(source, "example_application", "accepted_by_step7", decision)
                add_unique(final_app_nodes, item, node_identity)
            else:
                deferred.append(archived_item(source, "deferred_unknown_accept_target", decision, "node"))
                traces.append(trace_row(decision, "defer", note=f"unknown target_layer: {target_layer}"))
                continue
            traces.append(trace_row(decision, "accept", imported_item_id=node_identity(source)))
        elif recommendation == "rewrite":
            rewrite = decision.get("rewritten_item") or {}
            archived.append(
                archived_item(
                    source,
                    "rewritten_original_not_imported",
                    decision,
                    "node",
                    {"rewritten_item": rewrite},
                )
            )
            if rewrite.get("operation") == "merge_node":
                merged = merge_node_alias(final_core_nodes, str(rewrite.get("target_name") or ""), source, decision)
                note = "merged_into_existing_core_node" if merged else "merge_target_not_found_archive_only"
                traces.append(
                    trace_row(
                        decision,
                        "rewrite",
                        imported_item_id=str(rewrite.get("target_node_id") or rewrite.get("target_name") or ""),
                        archived_item_id=node_identity(source),
                        note=note,
                    )
                )
            else:
                traces.append(
                    trace_row(
                        decision,
                        "rewrite",
                        archived_item_id=node_identity(source),
                        note=str(decision.get("action_detail") or "rewritten_without_imported_node"),
                    )
                )
        elif recommendation == "reject":
            archived.append(archived_item(source, "rejected_by_step7", decision, "node"))
            traces.append(trace_row(decision, "reject", archived_item_id=node_identity(source)))
        else:
            deferred.append(archived_item(source, "deferred_after_step7", decision, "node"))
            traces.append(trace_row(decision, "defer", archived_item_id=node_identity(source)))

    nodes_by_name: dict[str, dict[str, Any]] = {}
    for node in [*final_core_nodes, *final_app_nodes]:
        name = str(node.get("name") or "")
        if name and name not in nodes_by_name:
            nodes_by_name[name] = node

    for decision in approved_decisions:
        if decision.get("item_kind") != "edge":
            continue
        source = dict(decision.get("source_item") or {})
        recommendation = str(decision.get("recommendation") or "")
        target_layer = str(decision.get("target_layer") or "")

        if recommendation == "accept":
            endpoints_ok, missing = edge_endpoints_exist(source, [*final_core_nodes, *final_app_nodes])
            if not endpoints_ok:
                deferred.append(
                    archived_item(
                        source,
                        "deferred_edge_endpoint_not_imported",
                        decision,
                        "edge",
                        {"missing_endpoints": missing},
                    )
                )
                traces.append(
                    trace_row(
                        decision,
                        "defer",
                        archived_item_id=edge_identity(source),
                        note="edge_endpoint_not_imported:" + ",".join(missing),
                    )
                )
                continue
            if is_core_target_layer(target_layer):
                item = final_edge(source, "core", "accepted_by_step7", decision)
                add_unique(final_core_edges, item, edge_identity)
            elif target_layer == "example_application":
                item = final_edge(source, "example_application", "accepted_by_step7", decision)
                add_unique(final_app_edges, item, edge_identity)
            else:
                deferred.append(archived_item(source, "deferred_unknown_accept_target", decision, "edge"))
                traces.append(trace_row(decision, "defer", note=f"unknown target_layer: {target_layer}"))
                continue
            traces.append(trace_row(decision, "accept", imported_item_id=edge_identity(source)))
        elif recommendation == "rewrite":
            rewrite = decision.get("rewritten_item") or {}
            if rewrite.get("operation") == "replace_edge":
                new_edge = enrich_rewritten_edge(rewrite, nodes_by_name)
                endpoints_ok, missing = edge_endpoints_exist(new_edge, [*final_core_nodes, *final_app_nodes])
                if not endpoints_ok:
                    deferred.append(
                        archived_item(
                            source,
                            "deferred_rewritten_edge_endpoint_not_imported",
                            decision,
                            "edge",
                            {"rewritten_item": new_edge, "missing_endpoints": missing},
                        )
                    )
                    traces.append(
                        trace_row(
                            decision,
                            "defer",
                            archived_item_id=edge_identity(source),
                            note="rewritten_edge_endpoint_not_imported:" + ",".join(missing),
                        )
                    )
                    continue
                item = final_edge(new_edge, str(new_edge.get("kg_layer") or "example_application"), "rewritten_by_step7", decision)
                added = add_unique(final_app_edges if item["kg_layer"] == "example_application" else final_core_edges, item, edge_identity)
                archived.append(
                    archived_item(
                        source,
                        "rewritten_original_not_imported",
                        decision,
                        "edge",
                        {"rewritten_item": item},
                    )
                )
                traces.append(
                    trace_row(
                        decision,
                        "rewrite",
                        imported_item_id=edge_identity(item),
                        archived_item_id=edge_identity(source),
                        note="rewritten_edge_imported" if added else "rewritten_edge_duplicate_skipped",
                    )
                )
            else:
                archived.append(archived_item(source, "rewrite_without_replacement_archived", decision, "edge"))
                traces.append(trace_row(decision, "rewrite", archived_item_id=edge_identity(source), note="missing replace_edge payload"))
        elif recommendation == "reject":
            archived.append(archived_item(source, "rejected_by_step7", decision, "edge"))
            traces.append(trace_row(decision, "reject", archived_item_id=edge_identity(source)))
        else:
            deferred.append(archived_item(source, "deferred_after_step7", decision, "edge"))
            traces.append(trace_row(decision, "defer", archived_item_id=edge_identity(source)))

    for decision in approved_decisions:
        if decision.get("item_kind") != "rule_case":
            continue
        source = dict(decision.get("source_item") or {})
        recommendation = str(decision.get("recommendation") or "")

        if recommendation == "accept":
            if not owner_exists(source, [*final_core_nodes, *final_app_nodes]):
                deferred.append(archived_item(source, "deferred_rule_case_owner_not_imported", decision, "rule_case"))
                traces.append(trace_row(decision, "defer", archived_item_id=rule_case_identity(source), note="owner_node_not_in_final_package"))
                continue
            item = final_rule_case(source, "accepted_by_step7", decision)
            added = add_unique(final_rule_cases, item, rule_case_identity)
            traces.append(
                trace_row(
                    decision,
                    "accept",
                    imported_item_id=rule_case_identity(item),
                    note="rule_case_imported" if added else "duplicate_rule_case_skipped",
                )
            )
        elif recommendation == "rewrite":
            rewrite = decision.get("rewritten_item") or {}
            archived.append(
                archived_item(
                    source,
                    "rewritten_original_not_imported",
                    decision,
                    "rule_case",
                    {"rewritten_item": rewrite},
                )
            )
            if rewrite.get("operation") == "replace_rule_case":
                new_case = dict(source)
                new_case.update({k: v for k, v in rewrite.items() if k != "operation"})
                if not new_case.get("rule_case_id"):
                    new_case["rule_case_id"] = rule_case_identity(new_case)
                if owner_exists(new_case, [*final_core_nodes, *final_app_nodes]):
                    item = final_rule_case(new_case, "rewritten_by_step7", decision)
                    added = add_unique(final_rule_cases, item, rule_case_identity)
                    traces.append(
                        trace_row(
                            decision,
                            "rewrite",
                            imported_item_id=rule_case_identity(item),
                            archived_item_id=rule_case_identity(source),
                            note="rewritten_rule_case_imported" if added else "rewritten_rule_case_duplicate_skipped",
                        )
                    )
                else:
                    deferred.append(archived_item(new_case, "deferred_rewritten_rule_case_owner_not_imported", decision, "rule_case"))
                    traces.append(
                        trace_row(
                            decision,
                            "defer",
                            archived_item_id=rule_case_identity(source),
                            note="rewritten_rule_case_owner_not_in_final_package",
                        )
                    )
            else:
                traces.append(
                    trace_row(
                        decision,
                        "rewrite",
                        archived_item_id=rule_case_identity(source),
                        note=str(decision.get("action_detail") or "rewritten_rule_case_without_replacement"),
                    )
                )
        elif recommendation == "reject":
            archived.append(archived_item(source, "rejected_by_step7", decision, "rule_case"))
            traces.append(trace_row(decision, "reject", archived_item_id=rule_case_identity(source)))
        else:
            deferred.append(archived_item(source, "deferred_after_step7", decision, "rule_case"))
            traces.append(trace_row(decision, "defer", archived_item_id=rule_case_identity(source)))

    section_groups, section_group_edges = build_section_groups([*final_core_nodes, *final_app_nodes])
    rule_groups, rule_group_edges = build_rule_groups(final_rule_cases)
    final_groups: list[dict[str, Any]] = []
    final_group_edges: list[dict[str, Any]] = []
    for group in [*section_groups, *rule_groups]:
        add_unique(final_groups, group, group_identity)
    for edge in [*section_group_edges, *rule_group_edges]:
        add_unique(final_group_edges, edge, group_member_identity)

    write_jsonl(out_dir / "final_core_nodes.jsonl", final_core_nodes)
    write_jsonl(out_dir / "final_core_edges.jsonl", final_core_edges)
    write_jsonl(out_dir / "final_application_nodes.jsonl", final_app_nodes)
    write_jsonl(out_dir / "final_application_edges.jsonl", final_app_edges)
    write_jsonl(out_dir / "final_rule_cases.jsonl", final_rule_cases)
    write_jsonl(out_dir / "final_knowledge_groups.jsonl", final_groups)
    write_jsonl(out_dir / "final_knowledge_group_edges.jsonl", final_group_edges)
    write_jsonl(out_dir / "final_archived_items.jsonl", archived)
    write_jsonl(out_dir / "final_rejected_items.jsonl", [row for row in archived if "reject" in str(row.get("archive_status") or "")])
    write_jsonl(out_dir / "final_review_pending.jsonl", deferred)
    write_jsonl(out_dir / "decision_trace.jsonl", traces)
    write_report(
        out_dir / "final_import_report.md",
        final_core_nodes,
        final_core_edges,
        final_app_nodes,
        final_app_edges,
        final_rule_cases,
        final_groups,
        final_group_edges,
        archived,
        deferred,
        traces,
    )

    print(f"[OK] final import package -> {out_dir}")
    print(f"[OK] core nodes/edges -> {len(final_core_nodes)}/{len(final_core_edges)}")
    print(f"[OK] application nodes/edges -> {len(final_app_nodes)}/{len(final_app_edges)}")
    print(f"[OK] rule cases -> {len(final_rule_cases)}")
    print(f"[OK] knowledge groups/edges -> {len(final_groups)}/{len(final_group_edges)}")
    print(f"[OK] archived/deferred -> {len(archived)}/{len(deferred)}")
    print(f"[OK] decision traces -> {len(traces)}")


if __name__ == "__main__":
    main()
