def expand_terms(terms: list[str], max_per: int = 3) -> list[str]:
    """为给定术语列表查找教材同义扩展词。

    Args:
        terms: 原始术语列表（通常来自 extract_phrases）
        max_per: 每个原始术语最多返回的扩展词数

    Returns:
        扩展后的术语列表（去重，保留最相关的扩展词）
    """
    expanded: list[str] = []
    for term in terms:
        expanded.append(term)
        mapping = TERMINOLOGY_MAP.get(term)
        if mapping:
            expanded.extend(mapping[1:max_per + 1])
    # 去重保序
    seen: set[str] = set()
    result: list[str] = []
    for t in expanded:
        if t not in seen and len(t) >= 2:
            seen.add(t)
            result.append(t)
    return result
