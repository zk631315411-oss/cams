"""
v4.4 Step 7B: apply approved review decisions.

This step turns Step 7A advisory decisions into final import packages. It does
not call an LLM and does not change Step 6 artifacts. Every non-imported item is
kept in an archive and every accepted / rewritten / rejected action is recorded
in decision_trace.jsonl.

v4.4 additionally creates deterministic KnowledgeGroup records after accepted
items are known. SectionGroup and RuleGroup are generated by code rather than
free LLM grouping.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from collections import Counter
from datetime import datetime
from pathlib import Path
from typing import Any


SCRIPT_DIR = Path(__file__).resolve().parent
DEFAULT_MIDDLE_DIR = SCRIPT_DIR / "中间产物"
DEFAULT_LAYER_DIR = DEFAULT_MIDDLE_DIR / "step6_layers"
DEFAULT_DECISIONS = DEFAULT_MIDDLE_DIR / "step7_preapproval" / "preapproval_decisions.jsonl"
DEFAULT_OUT_DIR = DEFAULT_MIDDLE_DIR / "step7_final_package"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Apply v4.4 Step 7 approved review decisions.")
    parser.add_argument("--layer-dir", type=Path, default=DEFAULT_LAYER_DIR)
    parser.add_argument("--decisions", type=Path, default=DEFAULT_DECISIONS)
    parser.add_argument("--out-dir", type=Path, default=DEFAULT_OUT_DIR)
    parser.add_argument(
        "--approval-label",
        default="user_approved_step7a",
        help="Human-readable label written into decision traces.",
    )
    return parser.parse_args()


def read_jsonl(path: Path, required: bool = True) -> list[dict[str, Any]]:
    if not path.exists():
        if required:
            raise FileNotFoundError(f"JSONL not found: {path}")
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8-sig").splitlines() if line.strip()]


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows), encoding="utf-8")


def stable_id(prefix: str, parts: list[str]) -> str:
    digest = hashlib.sha1("|".join(parts).encode("utf-8")).hexdigest()[:14]
    return f"{prefix}:{digest}"


def now_iso() -> str:
    return datetime.now().isoformat(timespec="seconds")


def source_code(row: dict[str, Any]) -> str:
    section_node_id = str(row.get("section_node_id") or "").strip()
    textbook_id = str(row.get("textbook_id") or "").strip()
    base = section_node_id or textbook_id or "unknown-source"
    line_start = row.get("line_start")
    line_end = row.get("line_end")
    if line_start not in (None, "", 0) or line_end not in (None, "", 0):
        return f"{base}:L{line_start or ''}-L{line_end or ''}"
    return base


def ensure_source_code(item: dict[str, Any]) -> dict[str, Any]:
    item.setdefault("source_code", source_code(item))
    return item


def node_identity(node: dict[str, Any]) -> str:
    node_id = str(node.get("node_id") or "")
    if node_id:
        return node_id
    return stable_id("node-key", [str(node.get("name") or ""), str(node.get("type") or "")])


def edge_identity(edge: dict[str, Any]) -> str:
    return stable_id(
        "edge-key",
        [
            str(edge.get("source_node_id") or edge.get("source_name") or ""),
            str(edge.get("target_node_id") or edge.get("target_name") or ""),
            str(edge.get("type") or ""),
            str(edge.get("kg_layer") or ""),
        ],
    )


def rule_case_identity(rule_case: dict[str, Any]) -> str:
    rule_case_id = str(rule_case.get("rule_case_id") or "")
    if rule_case_id:
        return rule_case_id
    return stable_id(
        "rule-case-key",
        [
            str(rule_case.get("owner_node_id") or rule_case.get("owner_name") or ""),
            str(rule_case.get("case_name") or ""),
            str(rule_case.get("evidence_span") or ""),
        ],
    )


def final_node(row: dict[str, Any], final_layer: str, status: str, decision: dict[str, Any] | None = None) -> dict[str, Any]:
    item = dict(row)
    item["kg_layer"] = final_layer
    item["rule_cases"] = []
    item["rule_cases_step7_policy"] = "rule_cases_are_reviewed_separately"
    item["step7_status"] = status
    item["step7_layer"] = final_layer
    item["final_import_ready"] = True
    item["step7_generated_at"] = now_iso()
    if decision:
        item["step7_decision_id"] = decision.get("decision_id", "")
        item["step7_basis"] = decision.get("basis", "")
        item["step7_approval_label"] = decision.get("approval_label", "")
    return ensure_source_code(item)


def final_edge(row: dict[str, Any], final_layer: str, status: str, decision: dict[str, Any] | None = None) -> dict[str, Any]:
    item = dict(row)
    item["kg_layer"] = final_layer
    item["step7_status"] = status
    item["step7_layer"] = final_layer
    item["final_import_ready"] = True
    item["step7_generated_at"] = now_iso()
    if decision:
        item["step7_decision_id"] = decision.get("decision_id", "")
        item["step7_basis"] = decision.get("basis", "")
        item["step7_approval_label"] = decision.get("approval_label", "")
    return ensure_source_code(item)


def final_rule_case(row: dict[str, Any], status: str, decision: dict[str, Any] | None = None) -> dict[str, Any]:
    item = dict(row)
    item["kg_layer"] = "rule_case"
    item["step7_status"] = status
    item["step7_layer"] = "rule_case"
    item["final_import_ready"] = True
    item["step7_generated_at"] = now_iso()
    if not item.get("rule_case_id"):
        item["rule_case_id"] = rule_case_identity(item)
    if decision:
        item["step7_decision_id"] = decision.get("decision_id", "")
        item["step7_basis"] = decision.get("basis", "")
        item["step7_approval_label"] = decision.get("approval_label", "")
    return ensure_source_code(item)


def archived_item(
    source: dict[str, Any],
    archive_status: str,
    decision: dict[str, Any] | None,
    item_kind: str | None = None,
    extra: dict[str, Any] | None = None,
) -> dict[str, Any]:
    item = dict(source)
    item["archive_status"] = archive_status
    item["final_import_ready"] = False
    item["step7_generated_at"] = now_iso()
    if item_kind:
        item["item_kind"] = item_kind
    if decision:
        item["step7_decision_id"] = decision.get("decision_id", "")
        item["step7_recommendation"] = decision.get("recommendation", "")
        item["step7_action_detail"] = decision.get("action_detail", "")
        item["step7_basis"] = decision.get("basis", "")
        item["step7_approval_label"] = decision.get("approval_label", "")
    if extra:
        item.update(extra)
    return item


